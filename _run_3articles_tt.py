BANNED_OPENINGS = ["刷到", "看到", "点开", "朋友圈", "群里", "评论区", "近日", "话说回来", "闲来无事"]
BANNED_CONNECTORS = ["首先", "其次", "最后", "总之", "综上所述", "不难看出", "值得一提的是"]
BANNED_PARALLEL = ["不仅是", "也是", "更是", "不仅是", "而且", "还"]
BANNED_ADJ = ["令人深思", "发人深省", "意义深远"]
ERHUA_WORDS = ["事儿", "点儿", "地儿", "哥们儿", "玩意儿"]

all_pass = True
for art in ARTICLES:
    text = art['content']
    first_sentences = text[:150]
    issues = []

    # A1: No banned patterns
    for bw in BANNED_OPENINGS:
        if bw in first_sentences:
            issues.append(f"A1: 开头含禁用词 '{bw}'")

    # A5: No AI flavor in opening
    for bw in BANNED_CONNECTORS:
        if bw in first_sentences:
            issues.append(f"A5: 开头含机械连接词 '{bw}'")

    # B1: No connectors in full text
    for bw in BANNED_CONNECTORS:
        if bw in text:
            issues.append(f"B1: 全文含机械连接词 '{bw}'")

    # B3: No empty adjectives
    for bw in BANNED_ADJ:
        if bw in text:
            issues.append(f"B3: 全文含空形容词 '{bw}'")

    # B9: Erhua check
    for ew in ERHUA_WORDS:
        if ew in text:
            issues.append(f"B9: 全文含儿化音 '{ew}'")

    if issues:
        all_pass = False
        print(f"  [{art['index']}] ✗ {art['title']}")
        for iss in issues:
            print(f"    {iss}")
    else:
        print(f"  [{art['index']}] ✓ {art['title']}")

if all_pass:
    print("\n✓ 维度A+B 全部通过")
else:
    print("\n✗ 维度A+B 有未通过项，需修正")

